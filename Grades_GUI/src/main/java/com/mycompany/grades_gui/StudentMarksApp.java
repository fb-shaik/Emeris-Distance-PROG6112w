    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
 try {
        // Step 1: Capture marks from the GUI.
        int[][] marks = captureMarks();
        // Step 2: Create a StudentMarks object.
        StudentMarks student = new StudentMarks(marks);
        // Step 3: Calculate the results.
        int total = student.GetTotalMarks();
        double average = student.GetAverageMarks();
        int passes = student.GetPassCount();
        int fails = student.GetFailCount();
        int students = student.GetStudentsProcessed();
        // Step 4: Build the results report.
        String report = "STUDENT MARKS REPORT\n";
        report += "****************************\n";
        report += "Total Marks: " + total + "\n";
        report += String.format(
                "Average Mark: %.2f\n", average);
        report += "Passing Marks: " + passes + "\n";
        report += "Failing Marks: " + fails + "\n";
        report += "Students Processed: " + students + "\n";
        report += "****************************";
        // Step 5: Display the report.
        txtResults.setText(report);
        // Step 6: Update the label.
        lblStudentsProcessed.setText(
                "Students Processed: " + students);
    }
 catch (NumberFormatException ex)
      {
        // Handle letters and empty fields.
        JOptionPane.showMessageDialog(
                this,
                "Please enter valid whole-number marks in all fields.",
                "Input Error",
                JOptionPane.ERROR_MESSAGE);

    } 
 catch (IllegalArgumentException ex) {

        // Handle marks outside the allowed range.
        JOptionPane.showMessageDialog(
                this,
                ex.getMessage(),
                "Invalid Mark",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnCalculateActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        try {
        // Capture and validate all marks.
        int[][] marks = captureMarks();
        // Create the object used for calculations.
        StudentMarks student = new StudentMarks(marks);
        // Create the text file.
        // Existing content will be overwritten.
        try (FileWriter writer = new FileWriter("studentmarks.txt")) {
            // Write the report heading.
            writer.write("STUDENT MARKS REPORT\n");
            writer.write("****************************\n");
            // Write each student's marks.
            for (int row = 0; row < marks.length; row++) {
                writer.write(
                        "Student " + (row + 1) + ": "
                        + marks[row][0] + ", "
                        + marks[row][1] + "\n");
            }
            // Add a blank line.
            writer.write("\n");
            // Write the calculated results.
            writer.write(
                    "Total Marks: "
                    + student.GetTotalMarks() + "\n");

            writer.write(String.format(
                    "Average Mark: %.2f\n",
                    student.GetAverageMarks()));

            writer.write(
                    "Passing Marks: "
                    + student.GetPassCount() + "\n");

            writer.write(
                    "Failing Marks: "
                    + student.GetFailCount() + "\n");

            writer.write(
                    "Students Processed: "
                    + student.GetStudentsProcessed() + "\n");

            writer.write("****************************\n");
        }

        // Show a success message.
        JOptionPane.showMessageDialog(
                this,
                "Student marks saved successfully!");

    } catch (NumberFormatException ex) {

        // Handle non-numeric or empty input.
        JOptionPane.showMessageDialog(
                this,
                "Please enter valid whole-number marks.",
                "Input Error",
                JOptionPane.ERROR_MESSAGE);

    } catch (IllegalArgumentException ex) {

        // Handle marks outside 0 to 100.
        JOptionPane.showMessageDialog(
                this,
                ex.getMessage(),
                "Invalid Mark",
                JOptionPane.ERROR_MESSAGE);

    } catch (IOException ex) {

        // Handle file-writing errors.
        JOptionPane.showMessageDialog(
                this,
                "Error saving file: " + ex.getMessage(),
                "File Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnLoadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadActionPerformed
      try {

        // Create an array to store loaded marks.
        int[][] marks = new int[3][2];

        // Open the saved file for reading.
        try (BufferedReader reader = new BufferedReader(
                new FileReader("studentmarks.txt"))) {

            // Read and skip the report heading.
            reader.readLine();

            // Read and skip the separator line.
            reader.readLine();

            // Read marks for all three students.
            for (int row = 0; row < 3; row++) {

                // Read the next student line.
                String line = reader.readLine();

                // Check that the line exists.
                if (line == null) {
                    throw new IOException(
                            "The file does not contain all student marks.");
                }

                // Separate the student label from the marks.
                String[] parts = line.split(":", 2);

                // Check the file format.
                if (parts.length != 2
                        || !parts[0].trim().equals(
                                "Student " + (row + 1))) {

                    throw new IOException(
                            "Invalid student record in the file.");
                }

                // Separate Test 1 and Test 2 using the comma.
                String[] values = parts[1].split(",");

                if (values.length != 2) {
                    throw new IOException(
                            "Invalid test marks in the file.");
                }

                // Convert the saved strings into integers.
                marks[row][0] =
                        Integer.parseInt(values[0].trim());

                marks[row][1] =
                        Integer.parseInt(values[1].trim());

                // Validate the loaded marks.
                for (int col = 0; col < 2; col++) {

                    if (marks[row][col] < 0
                            || marks[row][col] > 100) {

                        throw new IOException(
                                "The file contains an invalid mark.");
                    }
                }
            }
        }

        // Display Student 1's marks.
        txtStudent1Test1.setText(
                String.valueOf(marks[0][0]));

        txtStudent1Test2.setText(
                String.valueOf(marks[0][1]));

        // Display Student 2's marks.
        txtStudent2Test1.setText(
                String.valueOf(marks[1][0]));

        txtStudent2Test2.setText(
                String.valueOf(marks[1][1]));

        // Display Student 3's marks.
        txtStudent3Test1.setText(
                String.valueOf(marks[2][0]));

        txtStudent3Test2.setText(
                String.valueOf(marks[2][1]));

        // Recalculate and display the loaded results.
        btnCalculate.doClick();

        // Show confirmation.
        JOptionPane.showMessageDialog(
                this,
                "Student marks loaded successfully!");

    } catch (java.io.FileNotFoundException ex) {

        // Display an error if the file does not exist.
        JOptionPane.showMessageDialog(
                this,
                "No saved file found. Please save marks first.",
                "File Not Found",
                JOptionPane.ERROR_MESSAGE);

    } catch (IOException | NumberFormatException ex) {

        // Handle damaged files or invalid saved values.
        JOptionPane.showMessageDialog(
                this,
                "Error loading marks: " + ex.getMessage(),
                "Load Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnLoadActionPerformed

