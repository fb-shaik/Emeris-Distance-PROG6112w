private int[][] captureMarks() {

    // Create a 2D array for 3 students and 2 tests.
    int[][] marks = new int[3][2];

    // Read Student 1's marks.
    marks[0][0] = Integer.parseInt(txtStudent1Test1.getText().trim());
    marks[0][1] = Integer.parseInt(txtStudent1Test2.getText().trim());

    // Read Student 2's marks.
    marks[1][0] = Integer.parseInt(txtStudent2Test1.getText().trim());
    marks[1][1] = Integer.parseInt(txtStudent2Test2.getText().trim());

    // Read Student 3's marks.
    marks[2][0] = Integer.parseInt(txtStudent3Test1.getText().trim());
    marks[2][1] = Integer.parseInt(txtStudent3Test2.getText().trim());

    // Validate every mark.
    for (int row = 0; row < marks.length; row++) {

        for (int col = 0; col < marks[row].length; col++) {
            // Marks must be between 0 and 100.
            if (marks[row][col] < 0 || marks[row][col] > 100) {
                throw new IllegalArgumentException(
                        "Marks must be between 0 and 100.");
            }
        }
    }

    // Return the completed array.
    return marks;
}

  
